const path = require('node:path');
require('dotenv').config({ path: path.resolve(__dirname, '../.env') });
const { PrismaClient } = require('@prisma/client');
const bcrypt = require('bcryptjs');

const prisma = new PrismaClient();

async function ensureGlobalDemoSubject(code, name, description) {
  const existing = await prisma.subject.findFirst({ where: { ownerId: null, code } });
  if (!existing) {
    await prisma.subject.create({ data: { code, name, description } });
  }
}

async function main() {
  const categories = await Promise.all([
    prisma.category.upsert({
      where: { name: 'DEMO - Data Science' },
      update: {},
      create: {
        name: 'DEMO - Data Science',
        description: 'Seed example category; safe to replace with real catalog data.',
      },
    }),
    prisma.category.upsert({
      where: { name: 'DEMO - Computing' },
      update: {},
      create: {
        name: 'DEMO - Computing',
        description: 'Seed example category; safe to replace with real catalog data.',
      },
    }),
  ]);

  await Promise.all([
    ensureGlobalDemoSubject(
      'DEMO-DS101',
      'DEMO - Introduction to Data Science',
      'Example seed subject. Replace or remove before production use.',
    ),
    ensureGlobalDemoSubject(
      'DEMO-CS101',
      'DEMO - Computing Fundamentals',
      'Example seed subject. Replace or remove before production use.',
    ),
    prisma.book.upsert({
      where: { isbn: 'DEMO-ISBN-0001' },
      update: {},
      create: {
        isbn: 'DEMO-ISBN-0001',
        title: 'DEMO ONLY - Foundations of Data Science',
        author: 'Example Author',
        description: 'Demonstration record generated by the local Prisma seed script.',
        totalCopies: 3,
        availableCopies: 3,
        categories: { connect: { id: categories[0].id } },
      },
    }),
    prisma.book.upsert({
      where: { isbn: 'DEMO-ISBN-0002' },
      update: {},
      create: {
        isbn: 'DEMO-ISBN-0002',
        title: 'DEMO ONLY - Algorithms and Programming',
        author: 'Example Author',
        description: 'Demonstration record generated by the local Prisma seed script.',
        totalCopies: 2,
        availableCopies: 2,
        categories: { connect: { id: categories[1].id } },
      },
    }),
  ]);

  if (process.env.DEMO_STUDENT_ENABLED === 'true') {
    const email = process.env.DEMO_STUDENT_EMAIL?.trim().toLowerCase();
    const password = process.env.DEMO_STUDENT_PASSWORD;
    if (!email || !email.includes('@') || !password || Buffer.byteLength(password) < 12 || Buffer.byteLength(password) > 72) {
      throw new Error('Optional demo student seeding requires a valid DEMO_STUDENT_EMAIL and a 12-72 byte DEMO_STUDENT_PASSWORD.');
    }

    const demoName = 'Yasasvi (DEMO)';
    const existingUser = await prisma.user.findUnique({ where: { email } });
    if (existingUser && existingUser.name !== demoName) {
      throw new Error('The configured demo email belongs to a non-demo account. Choose a dedicated DEMO_STUDENT_EMAIL.');
    }

    const passwordHash = await bcrypt.hash(password, 12);
    const profile = {
      studentId: 'DEMO-YASASVI',
      program: 'B.Tech',
      department: 'CSE (Data Science)',
      year: '3rd Year',
    };
    if (existingUser) {
      await prisma.user.update({
        where: { id: existingUser.id },
        data: {
          passwordHash,
          studentProfile: {
            upsert: { update: profile, create: profile },
          },
        },
      });
    } else {
      await prisma.user.create({
        data: {
          name: demoName,
          email,
          passwordHash,
          role: 'STUDENT',
          studentProfile: { create: profile },
        },
      });
    }
    console.log('Optional Yasasvi (DEMO) student account seeded.');
  }

  console.log('Prisma demo seed complete. All inserted catalog records are labeled DEMO.');
}

main()
  .catch((error) => {
    console.error('Prisma demo seed failed', error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
